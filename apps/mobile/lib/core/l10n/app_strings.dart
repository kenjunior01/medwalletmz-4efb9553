/// Traduz uma chave para o locale dado (fallback: pt).
/// Consulta primeiro o dicionário original e depois a segunda vaga
/// de tradução (F8).
String tr(S key, String locale) {
  final value = _dict[locale]?[key] ?? _dictExtra[locale]?[key];
  if (value != null) return value;
  return _dict['pt']![key] ?? _dictExtra['pt']![key] ?? key.name;
}

/// Nome nativo do locale para os seletores.
String languageName(String code) {
  for (final l in appLanguages) {
    if (l.code == code) return '${l.flag} ${l.nativeName}';
  }
  return code;
}

/// Direcção do texto (RTL para árabe).
TextDirection textDirectionOf(String locale) =>
    locale == 'ar' ? TextDirection.rtl : TextDirection.ltr;
