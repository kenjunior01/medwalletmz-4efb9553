// Set nested keys in a flat JSON object
function setNestedKey(obj, keyPath, value) {
  const parts = keyPath.split('.');
  let current = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    if (!current[parts[i]]) current[parts[i]] = {};
    current = current[parts[i]];
  }
  current[parts[parts.length - 1]] = value;
}

const LOCALES = ['en', 'es', 'fr', 'hi', 'sw', 'af', 'am', 'pt-BR'];
let totalUpdated = 0;

for (const locale of LOCALES) {
  const filePath = path.join(LOCALE_DIR, `${locale}.json`);
  if (!fs.existsSync(filePath)) {
    console.log(`  ⚠  ${locale}.json not found, skipping`);
    continue;
  }

  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const translations = TRANSLATIONS[locale];
  let updated = 0;

  // Remove old worker and health_technician keys
  if (data.userType?.worker) {
    delete data.userType.worker;
    updated++;
  }
  if (data.userType?.health_technician) {
    delete data.userType.health_technician;
    updated++;
  }
  // Remove old technician from roleHome
  if (data.roleHome?.technician) {
    delete data.roleHome.technician;
    updated++;
  }

  // Add new keys
  for (const [key, value] of Object.entries(translations)) {
    const parts = key.split('.');
    let current = data;
    let exists = true;
    for (let i = 0; i < parts.length - 1; i++) {
      if (!current[parts[i]]) {
        exists = false;
        break;
      }
      current = current[parts[i]];
    }
    if (!exists || !current[parts[parts.length - 1]]) {
      setNestedKey(data, key, value);
      updated++;
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  totalUpdated += updated;
  console.log(`  ✅ ${locale}.json — ${updated} keys updated`);
}

console.log(`\nDone! ${totalUpdated} total keys updated across ${LOCALES.length} locales.`);
