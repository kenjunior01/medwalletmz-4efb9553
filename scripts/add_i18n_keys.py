# ─── MAIN LOGIC ─────────────────────────────────────────────────────────────────

LOCALES = ['pt', 'en', 'es', 'fr', 'hi', 'sw', 'af', 'am', 'pt-BR']

def deep_merge(base, override):
    """Recursively merge override into base."""
    result = copy.deepcopy(base)
    for key, value in override.items():
        if key in result and isinstance(result[key], dict) and isinstance(value, dict):
            result[key] = deep_merge(result[key], value)
        else:
            result[key] = copy.deepcopy(value)
    return result

for locale in LOCALES:
    filepath = os.path.join(LOCALE_DIR, f'{locale}.json')
    
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    if locale == 'pt':
        # Add all new namespaces from PT base
        for ns_name, ns_data in NEW_NS_PT.items():
            data[ns_name] = ns_data
    else:
        # Start with PT base, then override with locale-specific translations
        for ns_name, ns_data in NEW_NS_PT.items():
            base_ns = copy.deepcopy(ns_data)
            if locale in TRANSLATIONS and ns_name in TRANSLATIONS[locale]:
                base_ns = deep_merge(base_ns, TRANSLATIONS[locale][ns_name])
            data[ns_name] = base_ns
    
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    # Count total keys
    total = sum(len(v) if isinstance(v, dict) else 1 for v in data.values())
    print(f'{locale}: {total} keys ({len(data)} namespaces) - OK')

