def get_nested(obj, key_path):
    """Get value from nested dict using dot notation"""
    keys = key_path.split('.')
    current = obj
    for k in keys:
        if isinstance(current, dict) and k in current:
            current = current[k]
        else:
            return None
    return current


def set_nested(obj, key_path, value):
    """Set value in nested dict using dot notation"""
    keys = key_path.split('.')
    current = obj
    for k in keys[:-1]:
        if k not in current:
            current[k] = {}
        current = current[k]
    current[keys[-1]] = value


def get_all_keys(d, prefix=''):
    """Get all leaf key paths"""
    keys = []
    for k, v in d.items():
        full = f'{prefix}.{k}' if prefix else k
        if isinstance(v, dict):
            keys.extend(get_all_keys(v, full))
        else:
            keys.append(full)
    return keys


def main():
    # Load PT as source of truth
    pt = json.load(open(os.path.join(BASE_DIR, 'pt.json')))
    pt_keys = get_all_keys(pt)

    # All translation data combined
    ALL_TRANS = {}
    ALL_TRANS.update(TRANSLATIONS)
    ALL_TRANS.update(EXTRA_TRANSLATIONS)
    ALL_TRANS.update(REMAINING)

    # Now handle remaining sections that aren't in ALL_TRANS yet
    # These are: calendar, microInsurance, doctor, gamification, healthWallet, analytics, provinces, a11y, notifications
    
    # Add the remaining section translations
    for section in ['calendar', 'microInsurance', 'doctor', 'gamification', 'healthWallet', 'analytics', 'provinces', 'a11y', 'notifications']:
        if section not in ALL_TRANS:
            ALL_TRANS[section] = {}

    # Process each locale
    locales = ['es', 'fr', 'hi', 'sw', 'af', 'am', 'pt-BR']
    
    for locale in locales:
        filepath = os.path.join(BASE_DIR, f'{locale}.json')
        data = json.load(open(filepath))
        data_keys = set(get_all_keys(data))
        
        missing_keys = set(pt_keys) - data_keys
        
        if not missing_keys:
            print(f"{locale}: Already in sync!")
            continue
            
        print(f"{locale}: Adding {len(missing_keys)} missing keys...")
        
        for key in sorted(missing_keys):
            # Try to find translation in our database
            section = key.split('.')[0]
            sub_key = '.'.join(key.split('.')[1:])
            
            if section in ALL_TRANS and locale in ALL_TRANS[section]:
                trans_section = ALL_TRANS[section][locale]
                val = get_nested(trans_section, sub_key)
                if val is not None:
                    set_nested(data, key, val)
                    continue
            
            # Fallback: use PT value (better than nothing)
            pt_val = get_nested(pt, key)
            if pt_val is not None:
                set_nested(data, key, pt_val)
        
        # Write back
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write('\n')
        
        # Verify
        new_data = json.load(open(filepath))
        new_keys = set(get_all_keys(new_data))
        new_missing = set(pt_keys) - new_keys
        print(f"  -> Written. Remaining missing: {len(new_missing)}")

    # Verify en.json
    en = json.load(open(os.path.join(BASE_DIR, 'en.json')))
    en_keys = set(get_all_keys(en))
    en_missing = set(pt_keys) - en_keys
    print(f"\nen.json: Missing {len(en_missing)} keys")

    print("\nFinal key counts:")
    for locale in ['pt', 'en', 'es', 'fr', 'hi', 'sw', 'af', 'am', 'pt-BR']:
        data = json.load(open(os.path.join(BASE_DIR, f'{locale}.json')))
        print(f"  {locale}: {len(get_all_keys(data))} keys")


if __name__ == '__main__':
    main()
